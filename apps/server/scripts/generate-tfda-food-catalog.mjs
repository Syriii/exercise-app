/** Usage: node apps/server/scripts/generate-tfda-food-catalog.mjs official-json.zip
 * Offline generator. Source: https://data.gov.tw/dataset/8543 (OGDL-Taiwan-1.0).
 * Only the four declared per-100g fields are retained; missing values remain null.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import OpenCC from 'opencc-js';

const archive = process.argv[2];
if (!archive) throw new Error('Pass the official JSON ZIP path');
const names = execFileSync('unzip', ['-Z1', archive], { encoding: 'utf8' }).trim().split('\n');
if (names.length !== 1 || !/^20_\d+\.json$/.test(names[0])) throw new Error('Unexpected archive layout');
const records = JSON.parse(execFileSync('unzip', ['-p', archive, names[0]], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 }));
const simplified = OpenCC.Converter({ from: 'tw', to: 'cn' });
const categories = {
  '穀物類': 'grains', '澱粉類': 'grains', '蔬菜類': 'vegetables', '菇類': 'vegetables', '藻類': 'vegetables',
  '水果類': 'fruit', '肉類': 'meat_eggs', '魚貝類': 'meat_eggs', '蛋類': 'meat_eggs', '乳品類': 'dairy',
  '豆類': 'beans', '堅果及種子類': 'fats', '油脂類': 'fats', '加工調理食品及其他類': 'other',
  '調味料及香辛料類': 'other', '糕餅點心類': 'other', '飲料類': 'other', '糖類': 'other',
};
const fields = { '熱量': ['energyKcal', 'kcal'], '粗蛋白': ['proteinGrams', 'g'], '粗脂肪': ['fatGrams', 'g'], '總碳水化合物': ['carbohydrateGrams', 'g'] };
const aliases = { '白飯': '米饭 白米饭', '青花菜': '西兰花', '甘藍': '卷心菜 包菜 高丽菜', '馬鈴薯': '土豆', '白饅頭': '馒头', '豆漿(無糖)': '无糖豆浆' };
const categoryOverrides = { R2400201: 'grains', R2400101: 'grains', R2400301: 'grains', R2400501: 'grains', R2400601: 'grains', R4701201: 'beans', R4700901: 'beans', R4700902: 'beans', R4701001: 'beans', R4700401: 'beans', R5000101: 'beans', R5000301: 'beans' };
const foods = new Map();
for (const row of records) {
  const id = row['整合編號'], name = row['樣品名稱'];
  if (!/^[A-Z](?:\d{5}|\d{7})$/.test(id) || !name || !(row['食品分類'] in categories)) throw new Error('Unexpected food identity/category');
  const existing = foods.get(id);
  if (existing && existing.sourceLabel !== name) throw new Error(`Conflicting identity ${id}`);
  const description = row['內容物描述'] ?? '';
  const food = existing ?? { code: id, sourceLabel: name, label: simplified(name) + (/樣品狀態:生(?:[,;，；]|$)/.test(description) && !name.includes('(生)') ? '（生）' : ''),
    category: categoryOverrides[id] ?? categories[row['食品分類']], originalName: [name, row['樣品英文名稱'], description].filter(Boolean).join(' · '),
    aliases: simplified([row['俗名'], row['樣品英文名稱'], aliases[name]].filter(Boolean).join(' ')),
    energyKcal: null, proteinGrams: null, fatGrams: null, carbohydrateGrams: null, seen: new Set() };
  foods.set(id, food);
  const definition = fields[row['分析項']];
  if (!definition) continue;
  const [key, unit] = definition;
  if (row['含量單位'] !== unit || food.seen.has(key)) throw new Error(`Duplicate/wrong-unit nutrient ${id}/${key}`);
  food.seen.add(key);
  const raw = row['每100克含量'];
  if (raw === null || raw === undefined || String(raw).trim() === '') continue;
  const number = Number(raw);
  // The official record reports 100.3 g fat / 100 g. Do not silently clamp it.
  if (id === 'M9900201' && key === 'fatGrams' && number === 100.3) {
    food.originalName += ' · 原始粗脂肪100.3g/100g超出质量基准，本项保留未知';
    continue;
  }
  if (!Number.isFinite(number) || number < 0 || number > (key === 'energyKcal' ? 1000 : 100)) throw new Error(`Invalid nutrient ${id}/${key}`);
  food[key] = number;
}
const result = [...foods.values()].filter(f => [...Object.values(fields)].some(([key]) => f[key] !== null))
  .sort((a, b) => a.code.localeCompare(b.code)).map(({ sourceLabel, seen, ...food }) => food);
if (result.length < 2000) throw new Error('Unexpected source coverage drop');
const hash = createHash('sha256').update(readFileSync(archive)).digest('hex');
const target = fileURLToPath(new URL('../src/modules/nutrition/tfda-foods.generated.ts', import.meta.url));
writeFileSync(target, '// Generated by scripts/generate-tfda-food-catalog.mjs; do not hand-edit nutrient values.\n'
  + '// 衛生福利部食品藥物管理署 2026 食品營養成分資料集（2026-08-26导出）；OGDL-Taiwan-1.0.\n'
  + '// Attribution and modifications: docs/domain/food-catalog-sources.md\n'
  + `// Official ZIP SHA256: ${hash}\n`
  + 'import type { FoodCategory } from "./food-catalog.js";\n'
  + 'type TfdaFood = { code: string; label: string; category: FoodCategory; originalName: string; aliases: string; energyKcal: number | null; proteinGrams: number | null; fatGrams: number | null; carbohydrateGrams: number | null };\n'
  + 'const defineFood = (food: TfdaFood): TfdaFood => food;\nexport const tfdaFoods: readonly TfdaFood[] = [\n'
  + result.map(food => 'defineFood(' + JSON.stringify(food, null, 2) + ')').join(',\n') + '\n];\n');
console.log(JSON.stringify({ foods: result.length, hash, missingNutrients: result.filter(f => Object.values(fields).some(([key]) => f[key] === null)).length }));
